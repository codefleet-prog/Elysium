(function () {
    const STORAGE_KEY = 'elysium_lang';

    function getSavedLanguage() {
        return localStorage.getItem(STORAGE_KEY) || 'hu';
    }

    function setLanguage(lang) {
        if (!elysiumTranslations[lang]) return;

        localStorage.setItem(STORAGE_KEY, lang);
        document.documentElement.lang = lang;

        const dict = elysiumTranslations[lang];

        // 1. Text elements
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key] !== undefined) {
                // Check if element contains an icon or span child we should preserve
                const icon = el.querySelector('svg, span:not([data-i18n]), i');
                if (icon && el.childNodes.length > 1) {
                    // Find direct text node or text span
                    const textSpan = el.querySelector('.i18n-text');
                    if (textSpan) {
                        textSpan.innerHTML = dict[key];
                    } else {
                        // Replace text content while keeping icon
                        const clonedIcon = icon.cloneNode(true);
                        el.innerHTML = dict[key] + ' ';
                        el.appendChild(clonedIcon);
                    }
                } else {
                    el.innerHTML = dict[key];
                }
            }
        });

        // 2. Placeholder attributes
        document.querySelectorAll('[data-i18n-ph]').forEach(el => {
            const key = el.getAttribute('data-i18n-ph');
            if (dict[key] !== undefined) {
                el.placeholder = dict[key];
            }
        });

        // 3. Option elements inside selects
        document.querySelectorAll('option[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key] !== undefined) {
                el.textContent = dict[key];
            }
        });

        // 4. Update Language buttons active state
        document.querySelectorAll('.lang-btn').forEach(btn => {
            if (btn.dataset.lang === lang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });

        // 5. Dispatch custom event for dynamic components (like agency overlay)
        window.dispatchEvent(new CustomEvent('elysium:langchange', { detail: { lang } }));

        // 6. Refresh GSAP ScrollTrigger if present
        if (window.ScrollTrigger) {
            window.ScrollTrigger.refresh();
        }
    }

    function initLanguage() {
        const currentLang = getSavedLanguage();

        // Bind language toggle buttons
        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.addEventListener('click', (e) => {
                e.preventDefault();
                const targetLang = btn.dataset.lang;
                setLanguage(targetLang);
            });
        });

        // Initial application
        setLanguage(currentLang);
    }

    // Expose globally
    window.ElysiumLang = {
        setLanguage,
        getLanguage: getSavedLanguage,
        translations: elysiumTranslations
    };

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initLanguage);
    } else {
        initLanguage();
    }
})();
